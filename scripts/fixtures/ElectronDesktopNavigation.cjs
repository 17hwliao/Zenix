const {app,BrowserWindow}=require('electron');
const assert=require('node:assert/strict'),fs=require('node:fs/promises'),path=require('node:path');
if(!process.env.ZENIX_TEST_USER_DATA||!process.env.ZENIX_TEST_UI_URL)throw Error('Isolated fixture required');
app.setPath('userData',process.env.ZENIX_TEST_USER_DATA);
app.disableHardwareAcceleration();
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
app.whenReady().then(async()=>{
  const win=new BrowserWindow({show:false,width:1440,height:900,webPreferences:{offscreen:true,sandbox:true,contextIsolation:true,nodeIntegration:false,backgroundThrottling:false}});
  const errors=[];win.webContents.on('console-message',event=>{if(event.level==='error')errors.push(event.message);});
  const js=script=>win.webContents.executeJavaScript(script,true);
  const wait=async script=>{for(let i=0;i<180;i++){if(await js(script))return;await sleep(50);}throw Error('Timeout: '+script);};
  const click=selector=>js(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const input=(selector,value)=>js(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  const capture=async name=>{await js('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve(true))))');await sleep(350);win.webContents.invalidate();await sleep(100);await fs.writeFile(path.join(process.env.ZENIX_TEST_USER_DATA,name),(await win.webContents.capturePage()).toPNG());};
  await win.loadURL(process.env.ZENIX_TEST_UI_URL);
  await wait('!!document.querySelector(".zenix-desktop-home")');
  await js('window.originalDock=document.querySelector(".yz-playerbar--home")');
  const pages=[['liked','collection:liked'],['playlists','collection:playlists'],['history','collection:history'],['library','library:library'],['karaoke','tool:karaoke'],['tasks','tool:tasks'],['connections','tool:connections'],['assistant','tool:assistant']];
  for(const[id,page]of pages){
    await click(`[data-destination="${id}"]`);
    await wait(`document.querySelector('.zenix-desktop-workspace')?.dataset.workspace===${JSON.stringify(page)}`);
    await wait('!document.querySelector(".zenix-workspace-body [role=status]")||!document.querySelector(".zenix-workspace-spinner")');
    assert.equal(await js(`document.querySelector('[data-destination="${id}"]').getAttribute('aria-current')`),'page');
    assert.equal(await js('!!document.querySelector(".zenix-feature-backdrop,.yz-pl-backdrop,.zenix-manager[aria-modal=true]")'),false,'no legacy modal at '+id);
    assert.equal(await js('window.originalDock===document.querySelector(".yz-playerbar--home")'),true,'player remains mounted at '+id);
    if(['tasks','connections','assistant'].includes(id))await wait('!!document.querySelector(".zenix-feature-content section")');
    if(id==='karaoke')await wait('!!document.querySelector(".zenix-karaoke-modes")');
    if(['liked','history','library','tasks','connections','assistant'].includes(id))await capture(`desktop-${id}.png`);
    assert.equal(await js(`(()=>{const page=document.querySelector('.zenix-workspace-body'),nav=document.querySelector('.zenix-desktop-nav').getBoundingClientRect(),dock=document.querySelector('.yz-playerbar--home').getBoundingClientRect(),box=page.getBoundingClientRect();return page.scrollWidth<=page.clientWidth+1&&box.left>=nav.right&&box.bottom<=dock.top+1&&dock.right<=innerWidth+1;})()`),true,'page boundaries at '+id);
  }
  await click('[data-destination=liked]');
  await wait('!!document.querySelector(".zenix-manager-track")');
  assert.equal(await js('(()=>{const row=document.querySelector(".zenix-manager-track"),number=row.querySelector("button>span");return number.getBoundingClientRect().left-row.getBoundingClientRect().left<16;})()'),true,'track rows align with their toolbar');
  await click('.zenix-collection-tabs button:nth-child(2)');
  await wait('document.querySelectorAll(".zenix-manager-track").length===1');
  await click('.zenix-manager-track>button:first-child');
  assert.equal(await js('window.navigationFixture.plays.at(-1)'),'local-1');
  assert.equal(await js('document.querySelector("[data-destination=liked]").getAttribute("aria-current")'),'page');
  await click('[data-destination=playlists]');
  await click('.zenix-manager-overview-head button');
  await input('#zenix-playlist-name','写给明天');
  await js('window.navigationFixture.failCreate=true;document.querySelector(".zenix-manager-editor").requestSubmit()');
  await wait('document.querySelector(".zenix-manager-message")?.textContent.includes("隔离保存失败")');
  assert.equal(await js('document.querySelector("#zenix-playlist-name").value'),'写给明天');
  await js('window.navigationFixture.failCreate=false;document.querySelector(".zenix-manager-editor").requestSubmit()');
  await wait('document.querySelector(".zenix-manager main h2")?.textContent==="写给明天"&&!!document.querySelector(".zenix-manager-picker")');
  await click('.zenix-manager-picker-list>button');
  await wait('document.querySelectorAll(".zenix-manager-track").length===1');
  await capture('desktop-playlist-detail.png');
  await click('[data-destination=library]');
  await wait('document.querySelectorAll(".zenix-local-track").length===32');
  await input('[aria-label="搜索本地曲库"]','First Light');
  await wait('document.querySelectorAll(".zenix-local-track").length===1');
  await click('.zenix-local-track');
  assert.equal(await js('window.navigationFixture.plays.at(-1)'),'local-0');
  await click('.zenix-library-import-actions>button:first-child');
  await wait('window.navigationFixture.calls.some(call=>call.operation==="importFolder")');
  await click('.zenix-library-topline nav button:nth-child(2)');
  await wait('document.querySelector(".yz-pl-header h2")?.textContent==="磁盘歌单"');
  await capture('desktop-local-playlists.png');
  await js('window.dispatchEvent(new CustomEvent("zenix-open-workbench",{detail:{tab:"tasks"}}))');
  await wait('document.querySelector("[data-workspace=\\"tool:tasks\\"]")&&document.querySelector(".zenix-offline-tasks")');
  assert.equal(await js('document.querySelectorAll(".zenix-feature-workbench").length'),1,'external tool commands do not open duplicate hosts');
  await js('window.navigationFixture.failTasks=true');
  await wait('document.querySelector(".offline-message")?.textContent.includes("隔离任务服务暂不可用")');
  await click('[data-destination=connections]');
  await wait('!!document.querySelector(".zenix-connections")');
  await click('[data-destination=tasks]');
  await js('window.navigationFixture.failTasks=false');
  await wait('document.querySelector(".zenix-offline-tasks")?.textContent.includes("0.0 MiB")');
  win.setContentSize(860,720);await wait('Math.abs(innerWidth-860)<=1');await capture('desktop-tasks-narrow.png');
  assert.equal(await js('(()=>{const el=document.querySelector(".zenix-workspace-body");return el.scrollWidth<=el.clientWidth+1;})()'),true);
  await click('[data-destination=assistant]');await wait('!!document.querySelector(".zenix-figure-settings")');await capture('desktop-assistant-narrow.png');
  assert.equal(await js('(()=>{const el=document.querySelector(".zenix-workspace-body");return el.scrollWidth<=el.clientWidth+1;})()'),true);
  win.webContents.debugger.attach('1.3');
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]});
  assert.equal(await js('getComputedStyle(document.querySelector(".zenix-library-import-actions button")||document.querySelector(".zenix-workspace-breadcrumb button")).transitionDuration'),'0s');
  await click('.zenix-workspace-breadcrumb button');await wait('!!document.querySelector(".zenix-desktop-home")');
  assert.equal(await js('window.originalDock===document.querySelector(".yz-playerbar--home")'),true);
  await js('window.navigationFixture.probeWorkspace("collection:liked",true)');
  assert.equal(await js('!!document.querySelector("#workspace-probe [role=alert]")'),true);
  await js('window.navigationFixture.probeWorkspace("collection:history",false)');
  assert.equal(await js('!!document.querySelector("#workspace-probe [data-probe-recovered]")'),true,'a failed collection must not poison other collection pages');
  assert.deepEqual(errors,[],'no renderer errors');
  console.log('DESKTOP_NAVIGATION_UI_PASS');win.destroy();app.quit();
}).catch(error=>{console.error(error);app.exit(1);});
